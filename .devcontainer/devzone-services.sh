#!/usr/bin/env bash
# shellcheck shell=bash
# devzone, services of the cluster and their apply functions.
# Sourced by .devcontainer/devzone (split of the 1 600 lines file, #722):
# functions only, shared variables are defined in devzone.

# Runs a long command, writing "still running" every DEVZONE_PROGRESS s on
# stderr: a silent installation looks blocked (#195)
with_progress() {
    local step="${DEVZONE_PROGRESS:-30}" elapsed=0 pid code=0
    "$@" &
    pid=$!
    while kill -0 "$pid" 2>/dev/null; do
        sleep 1
        elapsed=$((elapsed + 1))
        if [ $((elapsed % step)) -eq 0 ] && kill -0 "$pid" 2>/dev/null; then
            echo "devzone : … still running (${elapsed} s)" >&2
        fi
    done
    wait "$pid" || code=$?
    return "$code"
}

# File that marks an active module in failure (content: where to look); next to
# the state, in its volume: the state shows it at each startup
failure_marker_file() {
    echo "$ETAT-failed-$1"
}

# Services in the Kubernetes workspace pod (#528): gitlab, postgres and argocd
# live in the cluster, installed from the workstation (devzone workspace
# services). The pod has no kubeconfig and a limited account (#430): their
# presence is the cluster DNS (like #515), never an installer failure marker.
in_pod() {
    [ "${DEVZONE_WORKSPACE:-}" = kubernetes ]
}

service_module() {
    case "$1" in
        gitlab | postgres | argocd) return 0 ;;
    esac
    return 1
}

# DNS name of the service of a module: <service>.<namespace>.svc
service_dns() {
    case "$1" in
        gitlab) echo "gitlab-webservice-default.devzone-gitlab${INSTANCE_SUFFIX}.svc" ;;
        postgres) echo "postgres.devzone-postgres.svc" ;;
        argocd) echo "argocd-server.devzone-argocd.svc" ;;
    esac
}

service_present() {
    getent hosts "$(service_dns "$1")" >/dev/null 2>&1
}

# Status line of a service module in the pod: present → active; absent → the
# workstation command that installs it
service_pod_line() {
    local m="$1"
    if service_present "$m"; then
        printf '  ✔ module %-10s active: %s (%s)\n' "$m" "$(description "$m")" "$(service_dns "$m")"
    elif [ "$(value_of "$m")" = on ]; then
        printf '  ⚠ module %-10s not in the cluster: on the workstation, devzone workspace services enable %s\n' "$m" "$m"
    else
        printf '  ○ module %-10s optional, %s: on the workstation, devzone workspace services enable %s\n' "$m" "$(description "$m")" "$m"
    fi
}

# devzone apply of a service module: in the Kubernetes workspace pod nothing
# is installed (the workstation does it, #528) and the failure marker of an
# earlier start is cleared; elsewhere, the installer of the module
apply_service() {
    if in_pod; then
        rm -f "$(failure_marker_file "$1")"
        echo "devzone: $1 is installed from the workstation (devzone workspace services enable $1): nothing to do in the pod"
        return 0
    fi
    "apply_$1" on
}

apply_kubernetes() {
    if [ "$1" = on ]; then
        bash "$ICI/kube-config.sh"
    else
        rm -f "$HOME/.kube/hote.config"
        # metrics-server removed from the clusters where devzone installed it
        # (devzone=installe marker set by metrics-server.sh); via its subcommand
        bash "$ICI/metrics-server.sh" retirer || true
        echo "devzone : kubernetes disabled"
    fi
}

apply_gitlab() {
    local current_state
    if [ "$1" = on ]; then
        # Skip if the state is ready and the runner online; otherwise install resumes
        current_state="$(devzone gitlab status)"
        if [[ "$current_state" == *"ready"* && "$current_state" == *"runner online"* ]]; then
            echo "devzone : gitlab already active, nothing to do."
            # /etc/hosts regenerated by Docker: gitlab.localhost is set again here too
            devzone gitlab hote-poser
            # Failure of an old run cleared: gitlab is ready (#366)
            rm -f "$(failure_marker_file gitlab)"
        else
            echo "devzone : activating gitlab via its installer…"
            if ! devzone gitlab install; then
                echo "gitlab" > "$(failure_marker_file gitlab)"
                return 1
            fi
            rm -f "$(failure_marker_file gitlab)"
        fi
    else
        # Disable gitlab only if its namespace still exists
        if devzone gitlab installe; then
            echo "devzone : deactivating gitlab…"
            if [ -n "${DELETE_DATA:-}" ]; then
                devzone gitlab uninstall --yes
            else
                devzone gitlab uninstall
            fi
        else
            echo "devzone : gitlab already deactivated (no devzone-gitlab namespace)."
        fi
    fi
}

# Shared PostgreSQL (#280): installed on the devzone cluster, chosen at the
# first activation (--context, terminal menu, dedicated kind otherwise)
apply_postgres() {
    local wanted="" confirm_ctx="" expect="" arg ctx actual current_state
    if [ "$1" = on ]; then
        for arg in "${@:2}"; do
            if [ -n "$expect" ]; then
                case "$expect" in
                    context) wanted="$arg" ;;
                    confirm) confirm_ctx="$arg" ;;
                esac
                expect=""
                continue
            fi
            case "$arg" in
                --context) expect=context ;;
                --confirm) expect=confirm ;;
                *) echo "devzone : unknown argument: $arg (devzone enable postgres --context CTX [--confirm CTX])" >&2; write_value postgres off; return 2 ;;
            esac
        done
        if [ -n "$expect" ]; then
            echo "devzone : $expect expects a context" >&2
            write_value postgres off
            return 2
        fi
        actual="$(cluster_saved)"
        if [ -n "$wanted" ] && [ -n "$actual" ] && [ "$wanted" != "$actual" ]; then
            echo "devzone : devzone services are on $actual; to change: devzone cluster $wanted" >&2
            write_value postgres off
            return 2
        fi
        if [ -n "$confirm_ctx" ]; then
            ctx="$(cluster_choose "$wanted" --confirm "$confirm_ctx")" || { write_value postgres off; return 2; }
        else
            ctx="$(cluster_choose "$wanted")" || { write_value postgres off; return 2; }
        fi
        # Choice kept before the installation: a resume targets the same cluster
        cluster_save "$ctx"
        current_state="$(devzone postgres status)"
        # "relay stopped" first: this line also starts with "ready on"
        if [[ "$current_state" == *"relay stopped"* ]]; then
            devzone postgres relay-start
            echo "devzone : postgres : relay restarted"
        elif [[ "$current_state" == "ready on"* ]]; then
            echo "devzone : postgres already active, nothing to do."
        elif ! devzone postgres install; then
            echo "postgres" >"$(failure_marker_file postgres)"
            return 1
        fi
        rm -f "$(failure_marker_file postgres)"
    else
        devzone postgres uninstall
        rm -f "$(failure_marker_file postgres)"
    fi
}

# Argo CD (#411): installed in the services cluster, access through the relay
# 127.0.0.1:8443; a failure is marked in the state and resumed by devzone apply
apply_argocd() {
    local current_state
    if [ "$1" = on ]; then
        current_state="$("$ICI/devzone" argocd status)"
        # "relay stopped" first: this line also starts with "ready"
        if [[ "$current_state" == *"relay stopped"* ]]; then
            "$ICI/devzone" argocd relay-start
            echo "devzone : argocd : relay restarted"
        elif [[ "$current_state" == "ready"* ]]; then
            echo "devzone : argocd already active, nothing to do."
        elif ! "$ICI/devzone" argocd install; then
            echo "argocd" >"$(failure_marker_file argocd)"
            return 1
        fi
        rm -f "$(failure_marker_file argocd)"
    else
        "$ICI/devzone" argocd uninstall
        rm -f "$(failure_marker_file argocd)"
    fi
}

# Catalog MySQL (#414): same logic as postgres (relay restarted if stopped),
# installation delegated to the Go module
apply_mysql() {
    local current_state ctx
    if [ "$1" = on ]; then
        ctx="$(cluster_saved)"
        if [ -z "$ctx" ]; then
            echo "devzone : mysql: no cluster chosen: devzone enable mysql" >&2
            write_value mysql off
            echo mysql >"$(failure_marker_file mysql)"
            return 2
        fi
        current_state="$(devzone mysql status)"
        # "relay stopped" first: this line also starts with "ready on"
        if [[ "$current_state" == *"relay stopped"* ]]; then
            devzone mysql relay-start
            echo "devzone : mysql: relay restarted"
        elif [[ "$current_state" == "ready on"* ]]; then
            echo "devzone : mysql already active, nothing to do."
        elif ! devzone mysql install; then
            echo mysql >"$(failure_marker_file mysql)"
            return 1
        fi
        rm -f "$(failure_marker_file mysql)"
    else
        # Removal without deleting the data: volume kept (#441); the databases
        # only leave with a yes (confirm_removal)
        bash "$ICI/catalog.sh" remove mysql
        if [ -n "${DELETE_DATA:-}" ]; then
            devzone mysql delete-data --yes
        fi
        rm -f "$(failure_marker_file mysql)"
    fi
}
