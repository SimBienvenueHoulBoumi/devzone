// writeFixture creates a file with the given content below root, with parents.
func writeFixture(t *testing.T, root, name, content string) {
	t.Helper()
	path := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

// newFixture builds a disposable devzone folder with the four module accounts
// used by the former password.bats tests. No real secret file is read.
func newFixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	writeFixture(t, root, "workspace/.gitlab/root-password", "mdp-test-root")
	writeFixture(t, root, "workspace/.gitlab/dev-password", "mdp-test-dev")
	writeFixture(t, root, "workspace/.postgres/admin-password", "mdp-test-admin")
	writeFixture(t, root, "workspace/.postgres/alpha.env", "DB_NAME=alpha\nDB_USER=alpha_user\nDB_PASSWORD=mdp-test-alpha\n")
	writeFixture(t, root, "workspace/.postgres/zeta.env", "DB_NAME=zeta\nDB_USER=zeta_user\nDB_PASSWORD=mdp-test-zeta\n")
	return root
}

// TestRegenerateContentsAndSort fixes the header, the tabs and the order of
// the grouped credentials file, field by field.
func TestRegenerateContentsAndSort(t *testing.T) {
	root := newFixture(t)
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(Path(root))
	if err != nil {
		t.Fatal(err)
	}
	want := "# devzone : identifiers of the accounts created by devzone. Plain-text secrets:\n" +
		"# never commit, copy or paste them into a ticket. Regenerated by devzone.\n" +
		"# service\taddress\tuser\tpassword\n" +
		"gitlab\thttp://gitlab.localhost:8929\tdev\tmdp-test-dev\n" +
		"gitlab\thttp://gitlab.localhost:8929\troot\tmdp-test-root\n" +
		"postgres\t127.0.0.1:5432\tpostgres\tmdp-test-admin\n" +
		"postgres:alpha\t127.0.0.1:5432/alpha\talpha_user\tmdp-test-alpha\n" +
		"postgres:zeta\t127.0.0.1:5432/zeta\tzeta_user\tmdp-test-zeta\n"
	if string(data) != want {
		t.Fatalf(".password = %q, want %q", data, want)
	}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.HasPrefix(line, "#") || line == "" {
			continue
		}
		if got := strings.Count(line, "\t"); got != 3 {
			t.Fatalf("entry has %d tabs: %q", got, line)
		}
	}
}

// TestRegenerateMode600 checks that the private view is never world readable.
func TestRegenerateMode600(t *testing.T) {
	root := newFixture(t)
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	info, err := os.Stat(Path(root))
	if err != nil {
		t.Fatal(err)
	}
	if got := info.Mode().Perm(); got != 0o600 {
		t.Fatalf("mode = %o, want 600", got)
	}
}

// TestRegenerateDropsRemovedAccount checks that a deleted account disappears
// from the regenerated view while the other accounts stay.
func TestRegenerateDropsRemovedAccount(t *testing.T) {
	root := newFixture(t)
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(root, "workspace/.gitlab/dev-password")); err != nil {
		t.Fatal(err)
	}
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(Path(root))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(data), "\tdev\t") {
		t.Fatalf("removed account still listed: %q", data)
	}
	if !strings.Contains(string(data), "gitlab\thttp://gitlab.localhost:8929\troot\tmdp-test-root\n") {
		t.Fatalf("remaining account missing: %q", data)
	}
}

// TestRegenerateRemovesFileWithoutAccount checks that no empty view is kept.
func TestRegenerateRemovesFileWithoutAccount(t *testing.T) {
	root := newFixture(t)
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	if err := os.RemoveAll(filepath.Join(root, "workspace")); err != nil {
		t.Fatal(err)
	}
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(Path(root)); !os.IsNotExist(err) {
		t.Fatalf(".password still present: %v", err)
	}
}

// TestRegenerateMysqlCatalogApps checks the MYSQL_* keys of a catalogue app.
func TestRegenerateMysqlCatalogApps(t *testing.T) {
	root := newFixture(t)
	writeFixture(t, root, "workspace/.mysql/datayer.env", "MYSQL_HOST=127.0.0.1\nMYSQL_PORT=3306\nMYSQL_USER=datayer\nMYSQL_PASSWORD=mdp-datayer\n")
	writeFixture(t, root, "workspace/.mysql/root.env", "MYSQL_HOST=127.0.0.1\nMYSQL_PORT=3306\nMYSQL_USER=root\nMYSQL_PASSWORD=mdproot\n")
	if err := Regenerate(root); err != nil {
		t.Fatal(err)
	}
	data, err := os.ReadFile(Path(root))
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range []string{
		"mysql:datayer\t127.0.0.1:3306\tdatayer\tmdp-datayer\n",
		"mysql:root\t127.0.0.1:3306\troot\tmdproot\n",
	} {
		if !strings.Contains(string(data), entry) {
			t.Fatalf("missing %q in %q", entry, data)
		}
	}
}

// TestRegenerateAtomicFailureKeepsPreviousFile checks that a failed
// replacement leaves the previous view and no temporary fragment behind, and
// that the error never carries a secret.
func TestRegenerateAtomicFailureKeepsPreviousFile(t *testing.T) {
	root := newFixture(t)
	if err := os.MkdirAll(Path(root), 0o755); err != nil {
		t.Fatal(err)
	}
	err := Regenerate(root)
	if err == nil {
		t.Fatal("expected a write failure")
	}
	if strings.Contains(err.Error(), "mdp-test") {
		t.Fatalf("secret in error: %q", err)
	}
	info, statErr := os.Stat(Path(root))
	if statErr != nil || !info.IsDir() {
		t.Fatalf("previous target replaced: %v", statErr)
	}
	items, readErr := os.ReadDir(root)
	if readErr != nil {
		t.Fatal(readErr)
	}
	for _, item := range items {
		if strings.HasPrefix(item.Name(), ".password.") {
			t.Fatalf("temporary fragment left: %s", item.Name())
		}
	}
}

// TestGitignoreIgnoresPassword is the Go equivalent of the removed bats test:
// the private view must never be committed.
func TestGitignoreIgnoresPassword(t *testing.T) {
	_, file, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("cannot locate the test file")
	}
	path := filepath.Join(filepath.Dir(file), "..", "..", ".gitignore")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, line := range strings.Split(string(data), "\n") {
		if strings.TrimSpace(line) == ".password" {
			return
		}
	}
	t.Fatalf(".password not ignored in %s", path)
}

// TestPathReturnsTarget checks the printed path even when no file exists.
func TestPathReturnsTarget(t *testing.T) {
	root := t.TempDir()
	if got, want := Path(root), filepath.Join(root, ".password"); got != want {
		t.Fatalf("Path = %q, want %q", got, want)
	}
	if _, err := os.Stat(Path(root)); !os.IsNotExist(err) {
		t.Fatalf("file created by Path: %v", err)
	}
}
